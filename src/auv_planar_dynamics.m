function dState = auv_planar_dynamics(state, control, params)
% AUV_PLANAR_DYNAMICS is a thin wrapper that preserves the Phase 1 interface
% while delegating to the numeric core implementation.

if nargin ~= 3
    error('auv_planar_dynamics:BadInput', 'Requires state, control, and params.');
end

dState = auv_planar_dynamics_core(...
    state, ...
    control(1), ...
    control(2), ...
    params.dynamics.massSurge, ...
    params.dynamics.massSway, ...
    params.dynamics.yawInertia, ...
    params.damping.Xu, ...
    params.damping.Xuu, ...
    params.damping.Yv, ...
    params.damping.Yvv, ...
    params.damping.YawLinear, ...
    params.damping.YawQuadratic);
end
