function control = auv_simple_controller_numeric(state, targetSpeed, targetHeading, p)
% AUV_SIMPLE_CONTROLLER_NUMERIC is the Simulink-friendly numeric controller.
% It does not call auv_params() or create a struct inside the MATLAB Function
% block; it calls the bare numeric core directly.

if numel(p) < 14
    error('auv_simple_controller_numeric:BadP', 'p must contain at least 14 numeric values.');
end

control = auv_simple_controller_core(...
    state, ...
    targetSpeed, ...
    targetHeading, ...
    p(1), ...
    p(4), ...
    p(5), ...
    p(10), ...
    p(11), ...
    p(12), ...
    p(13), ...
    p(14));
end
