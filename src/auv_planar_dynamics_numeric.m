function dState = auv_planar_dynamics_numeric(state, control, p)
% AUV_PLANAR_DYNAMICS_NUMERIC is the Simulink-friendly numeric entry point.
% It calls the core dynamics directly with bare numeric inputs and does not
% create a params struct inside the MATLAB Function block.

if numel(p) < 9
    error('auv_planar_dynamics_numeric:BadP', 'p must contain at least 9 numeric values.');
end

dState = auv_planar_dynamics_core(...
    state, ...
    control(1), ...
    control(2), ...
    p(1), ...
    p(2), ...
    p(3), ...
    p(4), ...
    p(5), ...
    p(6), ...
    p(7), ...
    p(8), ...
    p(9));
end
