function control = auv_simple_controller(state, targetSpeed, targetHeading, params)
% AUV_SIMPLE_CONTROLLER is a thin wrapper that preserves the Phase 1 interface
% while delegating to the numeric core implementation.

if nargin ~= 4
    error('auv_simple_controller:BadInput', 'Requires state, targetSpeed, targetHeading, and params.');
end

control = auv_simple_controller_core(...
    state, ...
    targetSpeed, ...
    targetHeading, ...
    params.dynamics.massSurge, ...
    params.damping.Xu, ...
    params.damping.Xuu, ...
    params.control.maxSpeed, ...
    params.control.maxYawRate, ...
    params.control.speedGain, ...
    params.control.kpYaw, ...
    params.control.kdYaw);
end
