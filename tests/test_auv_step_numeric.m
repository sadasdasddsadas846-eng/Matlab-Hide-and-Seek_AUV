classdef test_auv_step_numeric < matlab.unittest.TestCase
    methods (Test)
        function comparesToPhase1Equivalent(testCase)
            rng(42);
            paramsA = auv_agent_params('A');
            p = [paramsA.dynamics.massSurge; ...
                 paramsA.dynamics.massSway; ...
                 paramsA.dynamics.yawInertia; ...
                 paramsA.damping.Xu; ...
                 paramsA.damping.Xuu; ...
                 paramsA.damping.Yv; ...
                 paramsA.damping.Yvv; ...
                 paramsA.damping.YawLinear; ...
                 paramsA.damping.YawQuadratic; ...
                 paramsA.control.maxSpeed; ...
                 paramsA.control.maxYawRate; ...
                 paramsA.control.speedGain; ...
                 paramsA.control.kpYaw; ...
                 paramsA.control.kdYaw];

            for i = 1:5
                x = [randn * 5; randn * 5; deg2rad(randn * 60); randn; randn; randn * 0.5];
                targetSpeed = 0.5 + 0.8 * rand;
                targetHeading = deg2rad(-30 + 60 * rand);
                u = [targetSpeed; targetHeading; p];

                expectedControl = auv_simple_controller(x, targetSpeed, targetHeading, paramsA);
                expected = auv_planar_dynamics(x, expectedControl, paramsA);
                actual = auv_step_numeric(x, u);

                testCase.verifyEqual(actual, expected, 'AbsTol', 1e-10);
            end
        end
    end
end
